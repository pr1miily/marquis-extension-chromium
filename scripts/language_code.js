  function initLanguageCode() {
    const langCodeInput = document.getElementById("langCodeInput");
    const langCodeResult = document.getElementById("langCodeResult");
  
    if (!langCodeInput || !langCodeResult) return; // ✅ Guard
  
    function updateResults() {
        const input = langCodeInput.value.trim().toLowerCase();
        const results = langCodeData.filter(entry =>
            entry.code.toLowerCase().includes(input) ||
            entry.name.toLowerCase().includes(input)
        );
  
        langCodeResult.innerHTML = "";

        if (results.length === 0) {
            langCodeResult.innerHTML = '<div class="list-group-item text-muted text-center fst-italic">No match found.</div>';
        } else {
            results.forEach(entry => {
                const row = document.createElement("div");
                // ✅ FIX T3: Added bg-body text-body for theme compatibility
                row.className = "list-group-item d-flex gap-3 bg-body text-body";
                row.innerHTML = `<strong style="min-width: 4.5rem;">${entry.code}</strong><span>${entry.name}</span>`;
                langCodeResult.appendChild(row);
            });
        }
    }

    langCodeInput.addEventListener('input', updateResults);
    updateResults(); // empty input matches everything, so the full list shows on open
  }
  
  // ─── Lazy-load entry point ────────────────────────────────────────────────────
  document.addEventListener('marquis:sectionReady', (e) => {
      if (e.detail.sectionId === 'languageCodeSection') initLanguageCode();
  });
  
  document.addEventListener('DOMContentLoaded', () => {
      if (document.getElementById('langCodeInput')) initLanguageCode();
  });